/**
 * Generates src/data/land-dots.ts: a bitset marking which points of a
 * Fibonacci sphere fall on land. The globe rebuilds the points at runtime,
 * so the shipped data is a few KB instead of a coastline dataset.
 *
 * Run: node scripts/gen-land-dots.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';

const N = 20000;
const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);

const bits = new Uint8Array(Math.ceil(N / 8));
const golden = Math.PI * (3 - Math.sqrt(5));
let count = 0;
for (let i = 0; i < N; i++) {
    // Must match fibonacciPoint() in src/scripts/globe.ts
    const y = 1 - 2 * (i + 0.5) / N;
    const r = Math.sqrt(1 - y * y);
    const x = Math.cos(i * golden) * r, z = Math.sin(i * golden) * r;
    const lat = Math.asin(y) * 180 / Math.PI;
    const lon = Math.atan2(-z, x) * 180 / Math.PI;
    if (geoContains(land, [lon, lat])) {
        bits[i >> 3] |= 1 << (i & 7);
        count++;
    }
}

writeFileSync('src/data/land-dots.ts', `// Generated by scripts/gen-land-dots.mjs — do not edit.
// Bit i set = point i of a ${N}-point Fibonacci sphere is on land (${count} points).
export const LAND_POINTS = ${N};
export const LAND_BITS = '${Buffer.from(bits).toString('base64')}';
`);
console.log(`${count}/${N} land points, ${bits.length} bytes`);
